"""Collect the long-history daily data set (DATA ONLY — no returns, no signal statistics).

Writes immutable raw responses and normalized CSVs under the longhist data root (default
<main checkout>/data/external/longhist, override with --root or $LONGHIST_DIR), rewrites
manifest.json there, and writes the committed public event calendar config/longhist_events_v1.yaml.

The FRED API key is read from $FRED_API_KEY or the main checkout's .env; it is never printed or stored
(stored URLs carry api_key=<redacted>).
"""
from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

import yaml

from src.longhist import default_root
from src.longhist import fetch as F
from src.longhist import normalize as N


def fred_key(root: Path) -> str:
    key = os.environ.get("FRED_API_KEY")
    if key:
        return key
    env = root.parents[2] / ".env"  # <main>/data/external/longhist -> <main>/.env
    for line in env.read_text().splitlines():
        if line.strip().startswith("FRED_API_KEY="):
            return line.split("=", 1)[1].strip().strip('"').strip("'")
    raise SystemExit("FRED_API_KEY not found in environment or .env")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--root", type=Path, default=None)
    ap.add_argument("--events-out", type=Path, default=ROOT / "config" / "longhist_events_v1.yaml")
    a = ap.parse_args()
    root = a.root or default_root()
    root.mkdir(parents=True, exist_ok=True)
    man = F.Manifest(root)
    http = F.Http()
    failures = []

    # network (OSError incl. URLError/timeouts) and parse (ValueError/KeyError/IndexError/TypeError)
    # failures are recorded and the run continues: a missing series is reported, not fatal
    errs = (OSError, ValueError, KeyError, IndexError, TypeError)
    for sym in F.YAHOO_SYMBOLS:
        try:
            F.fetch_yahoo(http, root, man, sym, print)
        except errs as exc:
            failures.append({"source": "yahoo", "item": sym, "error": f"{type(exc).__name__}: {exc}"})
            print(f"yahoo {sym}: FAILED {type(exc).__name__}: {exc}")
    for name, url in F.CBOE.items():
        try:
            F.fetch_cboe(http, root, man, name, url, print)
        except errs as exc:
            failures.append({"source": "cboe", "item": name, "error": f"{type(exc).__name__}: {exc}"})
            print(f"cboe {name}: FAILED {type(exc).__name__}: {exc}")
    try:
        F.fetch_dix(http, root, man, print)
    except errs as exc:
        failures.append({"source": "squeezemetrics", "item": "DIX", "error": f"{type(exc).__name__}: {exc}"})
        print(f"dix: FAILED {type(exc).__name__}: {exc}")

    key = fred_key(root)
    try:
        fred = F.fetch_fred(http, root, man, key, print)
    except (*errs, RuntimeError) as exc:  # never echo the key
        raise SystemExit(f"FRED fetch failed: {type(exc).__name__}: {str(exc).replace(key, '<redacted>')}")
    fetched = N.utc_now()
    fomc, unresolved = F.fetch_fomc(http, root, man, int(fetched[:4]), print)
    days = F.build_calendar(root, man)

    ev = F.events_yaml(fred, fomc, unresolved, days, fetched)
    ev["fetch_failures"] = failures
    text = yaml.safe_dump(ev, sort_keys=False, allow_unicode=True, width=120)
    if key in text:
        raise SystemExit("refusing to write events yaml containing the API key")
    a.events_out.write_text("# Generated by scripts/longhist_fetch.py — public dates only. Do not hand-edit.\n" + text)
    man.data["fetch_failures"] = failures
    man.data["last_run_utc"] = fetched
    sha = man.save()
    if key in man.path.read_text():
        raise SystemExit("manifest contains the API key — aborting")
    print(f"events -> {a.events_out}")
    print(f"manifest {man.path} sha256={sha} files={len(man.data['files'])} failures={len(failures)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
